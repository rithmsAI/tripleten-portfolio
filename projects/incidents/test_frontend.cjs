const assert=require('node:assert/strict');
const {filteredLogs,canTransition,reportText,restoreState}=require('./workbench.js');
const sample={id:'INC-TEST',title:'Fixture',status:'open',service:'Identity',severity:'SEV2',owner:'Demo',impact:'Fictional',hypothesis:'Stale key',checks:[false,false,false],steps:['A','B','C'],logs:[{at:'14:00',level:'ERROR',message:'Keyset k17 mismatch'},{at:'14:01',level:'INFO',message:'Recovery'}],audit:[{seq:1,at:'UTC',action:'note',detail:'Observed mismatch'}]};
assert.equal(filteredLogs(sample,'ERROR','KEYSET').length,1);
assert.equal(filteredLogs(sample,'INFO','keyset').length,0);
assert.equal(filteredLogs(sample,'ALL','').length,2);
assert.ok(canTransition(sample,'resolved','A sufficiently long rationale'));
assert.ok(canTransition(sample,'investigating','short'));
assert.equal(canTransition(sample,'investigating','Inspecting the sample evidence.'),'');
assert.ok(canTransition({...sample,status:'mitigated'},'resolved','Verified all fictional probes.'));
assert.equal(canTransition({...sample,status:'mitigated',checks:[true,true,true]},'resolved','Verified all fictional probes.'),'');
assert.match(reportText(sample),/\[ \] A/);
assert.match(reportText(sample),/Observed mismatch/);
assert.match(reportText(sample),/not a tamper-proof/);
const seeds=[structuredClone(sample)];
const fresh=restoreState(seeds,null);
fresh.incidents[0].owner='Changed';
fresh.incidents[0].checks[0]=true;
fresh.incidents[0].audit.push({seq:2,at:'UTC',action:'note',detail:'New note'});
assert.equal(seeds[0].owner,'Demo');
assert.equal(seeds[0].checks[0],false);
assert.equal(seeds[0].audit.length,1);
assert.deepEqual(restoreState(seeds,null).incidents,seeds);
const saved={incidents:structuredClone(seeds),seq:999};
const restored=restoreState(seeds,saved);
assert.equal(restored.seq,1);
restored.incidents[0].audit[0].detail='Edited';
assert.equal(saved.incidents[0].audit[0].detail,'Observed mismatch');
assert.throws(()=>restoreState(seeds,{incidents:[{...sample,owner:42}]}),/Invalid/);
assert.throws(()=>restoreState(seeds,{incidents:[{...sample,status:'resolved'}]}),/Invalid/);
assert.throws(()=>restoreState(seeds,{incidents:[{...sample,audit:[{...sample.audit[0],seq:Infinity}]}]}),/Invalid/);
assert.throws(()=>restoreState(seeds,{incidents:[{...sample,audit:[sample.audit[0],sample.audit[0]]}]}),/Invalid/);
assert.throws(()=>restoreState(seeds,{incidents:[null]}),/Invalid/);
console.log('PASS: 22 frontend assertions covering filtering, workflow, reports, reset isolation and saved-state validation.');
